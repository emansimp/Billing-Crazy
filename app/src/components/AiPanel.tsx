"use client";
import { useEffect, useState } from "react";

type Resp = { provider: string; configured: boolean; blocked: boolean; text: string | null; citedIds: string[]; warnings: string[]; checks: { amounts: number; quantities: number; citations: number }; fallbackText: string | null; error?: string };
type Status = { configured: boolean; provider: string; model?: string };

export default function AiPanel({ displayId, baseText }: { displayId: string; baseText: string }) {
  const [status, setStatus] = useState<Status | null>(null);
  const [busy, setBusy] = useState<string | null>(null);
  const [out, setOut] = useState<{ label: string; r: Resp } | null>(null);
  useEffect(() => { fetch("/api/ai/status").then((r) => r.json()).then(setStatus).catch(() => setStatus({ configured: false, provider: "template" })); }, []);
  const configured = !!status?.configured;

  async function call(label: string, path: string, body: unknown) {
    setBusy(label); setOut(null);
    const res = await fetch(path, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
    const r = (await res.json()) as Resp & { error?: string };
    setBusy(null); setOut({ label, r });
  }
  const btn = (label: string, path: string, body: unknown) => (
    <button className="btn" type="button" disabled={busy !== null} onClick={() => call(label, path, body)} title={configured ? undefined : "AI not configured: shows the deterministic template text"}>{busy === label ? "Working…" : label}</button>
  );
  return (
    <div>
      <div style={{ display: "flex", justifyContent: "space-between", gap: 12, flexWrap: "wrap", alignItems: "center" }}>
        <h2 style={{ margin: 0, fontSize: 16, fontWeight: 600 }}>Plain-language explanation</h2>
        <span className="chip c-gray">{configured ? `AI provider: ${status?.provider}${status?.model ? ` (${status.model})` : ""}` : "Templated, AI provider not configured"}</span>
      </div>
      <div style={{ marginTop: 10, padding: 14, borderRadius: 8, background: "#F8F9FB", border: "1px dashed #C9CFD8" }}>{baseText}</div>
      <div style={{ marginTop: 12, display: "flex", flexWrap: "wrap", gap: 8, alignItems: "center" }}>
        {btn("Rewrite with AI", "/api/ai/explain", { finding: displayId })}
        {btn("Draft request to Billing", "/api/ai/memo", { finding: displayId, kind: "billing" })}
        {btn("Draft note to Controller", "/api/ai/memo", { finding: displayId, kind: "controller" })}
        {!configured && <span className="muted" style={{ fontSize: 12 }}>AI not configured: buttons render the template text.</span>}
      </div>
      {out && (
        <div style={{ marginTop: 12, border: `1px solid ${out.r.blocked || out.r.error ? "#E0A18C" : "#C9CFD8"}`, borderRadius: 8, padding: 12, background: "#fff" }} role="status">
          <div style={{ display: "flex", justifyContent: "space-between", flexWrap: "wrap", gap: 8, marginBottom: 6 }}>
            <b>{out.label}</b><span className="muted" style={{ fontSize: 12 }}>{out.r.provider === "template" ? "AI not configured: template text" : `Generated by ${out.r.provider}`}</span>
          </div>
          {out.r.error && <div style={{ color: "#8F2D0F", marginBottom: 6 }}>{out.r.error}</div>}
          {out.r.blocked && (
            <div style={{ background: "#FBE9E3", color: "#8F2D0F", padding: 10, borderRadius: 6, marginBottom: 8 }}>
              <b>Output blocked by the amount check.</b> The AI wrote a figure or citation that is not in the calculation, so its text is withheld.
              <ul style={{ margin: "6px 0 0 18px" }}>{out.r.warnings.map((w, i) => <li key={i}>{w}</li>)}</ul>
            </div>
          )}
          {(out.r.text ?? out.r.fallbackText) && <div style={{ whiteSpace: "pre-wrap" }}>{out.r.text ?? out.r.fallbackText}</div>}
          {!out.r.text && out.r.fallbackText && <div className="muted" style={{ fontSize: 12, marginTop: 6 }}>Showing the guard-checked template text instead.</div>}
          {out.r.text && <div className="muted" style={{ fontSize: 12, marginTop: 8 }}>Checked: {out.r.checks.amounts} amounts and {out.r.checks.quantities} run counts match the calculation; {out.r.checks.citations} citations verified{out.r.citedIds.length ? ` (${out.r.citedIds.join(", ")})` : ""}.</div>}
        </div>
      )}
    </div>
  );
}
